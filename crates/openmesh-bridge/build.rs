//! Build-time embedding for docs that must ship inside the bridge binary:
//!
//! * `content/help/*.md` + `content/help/index.json` → the help API, MCP `openmesh_help` and
//!   `openmesh://help/*` resources (AI-NATIVE.md §1.2, ux-help-system.md §5).
//! * `docs/api/openapi.json` → `GET /api/openapi.json` (AI-NATIVE.md §3.4).
//!
//! The generated `help_embedded.rs` is included by `src/help.rs`. Missing content degrades to an
//! empty table instead of failing the build (the docs workstream fills the corpus).

use std::env;
use std::fs;
use std::path::{Path, PathBuf};

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    // crates/openmesh-bridge -> repository root
    let root = manifest
        .parent()
        .and_then(Path::parent)
        .map(Path::to_path_buf)
        .unwrap_or_else(|| manifest.clone());
    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR"));

    println!("cargo:rerun-if-changed=build.rs");
    embed_help(&root, &out_dir);
    embed_openapi(&root, &out_dir);
}

fn embed_help(root: &Path, out_dir: &Path) {
    let help_dir = root.join("content").join("help");
    println!("cargo:rerun-if-changed={}", help_dir.display());

    let mut entries: Vec<(String, PathBuf)> = Vec::new();
    if let Ok(read_dir) = fs::read_dir(&help_dir) {
        for entry in read_dir.flatten() {
            let path = entry.path();
            if path.extension().and_then(|e| e.to_str()) != Some("md") {
                continue;
            }
            let Some(stem) = path.file_stem().and_then(|s| s.to_str()) else {
                continue;
            };
            println!("cargo:rerun-if-changed={}", path.display());
            entries.push((stem.to_string(), path));
        }
    }
    entries.sort_by(|a, b| a.0.cmp(&b.0));

    let index_path = help_dir.join("index.json");
    println!("cargo:rerun-if-changed={}", index_path.display());
    let index_json = fs::read_to_string(&index_path)
        .unwrap_or_else(|_| "{\"version\":1,\"topics\":[]}".to_string());
    let index_out = out_dir.join("help_index.json");
    let _ = fs::write(&index_out, index_json);

    let mut generated = String::new();
    generated.push_str("// @generated by build.rs — do not edit by hand.\n");
    generated.push_str(
        "pub const INDEX_JSON: &str = include_str!(concat!(env!(\"OUT_DIR\"), \"/help_index.json\"));\n",
    );
    generated.push_str("pub const SLUGS: &[&str] = &[\n");
    for (slug, _) in &entries {
        generated.push_str(&format!("    {slug:?},\n"));
    }
    generated.push_str("];\n\n");
    generated.push_str("pub fn embedded_markdown(slug: &str) -> Option<&'static str> {\n");
    generated.push_str("    match slug {\n");
    for (slug, path) in &entries {
        // `include_str!` with an absolute path keeps the generated file self-contained.
        generated.push_str(&format!(
            "        {slug:?} => Some(include_str!({:?})),\n",
            path.display().to_string()
        ));
    }
    generated.push_str("        _ => None,\n    }\n}\n");
    let _ = fs::write(out_dir.join("help_embedded.rs"), generated);
}

fn embed_openapi(root: &Path, out_dir: &Path) {
    let path = root.join("docs").join("api").join("openapi.json");
    println!("cargo:rerun-if-changed={}", path.display());
    let openapi = fs::read_to_string(&path).unwrap_or_else(|_| {
        "{\"openapi\":\"3.1.0\",\"info\":{\"title\":\"OpenMesh Bridge API\",\"version\":\"0.3.0\"},\"paths\":{}}"
            .to_string()
    });
    let _ = fs::write(out_dir.join("openapi.json"), openapi);
    let mut generated = String::from("// @generated by build.rs — do not edit by hand.\n");
    generated.push_str(
        "pub const OPENAPI_JSON: &str = include_str!(concat!(env!(\"OUT_DIR\"), \"/openapi.json\"));\n",
    );
    let _ = fs::write(out_dir.join("openapi_embedded.rs"), generated);
}
