 */
class FfiEngineBridgeUnavailable : EngineBridge {
    private val _status = MutableStateFlow(
        CoreStatus(running = false, error = "OpenMesh core not linked in this build"),
    )
    override val status: StateFlow<CoreStatus> = _status.asStateFlow()
    private val _events = MutableSharedFlow<CoreEvent>(extraBufferCapacity = 8)
    override val events: SharedFlow<CoreEvent> = _events.asSharedFlow()

    override suspend fun start() {
        _status.value = CoreStatus(running = false, error = "OpenMesh core not linked; see apps/android/README.md")
    }

    override suspend fun stop() = Unit

    override suspend fun sendText(targetId: String, text: String, channel: Boolean): Result<Long> =
        Result.failure(IllegalStateException("OpenMesh core not linked in this build"))

    override suspend fun ingest(frame: ByteArray, rssi: Int?, snr: Float?) = Unit

    override suspend fun nodes(): List<NodeInfo> = emptyList()
    override suspend fun messages(peerId: String): List<Message> = emptyList()
    override fun selfNodeId(): String? = null
}
