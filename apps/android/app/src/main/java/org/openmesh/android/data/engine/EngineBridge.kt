/**
 * Boundary to the OpenMesh protocol core.
 *
 * The shipping implementation will be generated by UniFFI from `crates/openmesh-ffi`
 * (`create`, `send_text`, `ingest`, `tick`, `nodes`, returning events + outbound frames), so the Kotlin app never
 * re-implements OMP framing or cryptography. Until that bridge is generated (M2), the
 * repository uses [DemoEngineBridge]; the interface exists so the swap is mechanical and the
 * UI/repository code does not change.
 */
interface EngineBridge {
    val status: StateFlow<CoreStatus>
    val events: SharedFlow<CoreEvent>

    suspend fun start()
    suspend fun stop()

    /** Send a text DM/channel message; returns the OMP message id. */
    suspend fun sendText(targetId: String, text: String, channel: Boolean = false): Result<Long>

    /** Feed one complete OMP frame received from the radio/bridge. */
    suspend fun ingest(frame: ByteArray, rssi: Int? = null, snr: Float? = null)

    suspend fun nodes(): List<NodeInfo>
    suspend fun messages(peerId: String): List<Message>

    /** The identity's public node id (hex), once the engine is started. */
    fun selfNodeId(): String?
}

data class CoreStatus(
    val running: Boolean = false,
    val nodeIdHex: String? = null,
    val knownNodes: Int = 0,
    val txFrames: Long = 0,
    val rxFrames: Long = 0,
    val storedEnvelopes: Int = 0,
    val error: String? = null,
)

sealed interface CoreEvent {
    data class MessageReceived(val message: Message) : CoreEvent
    data class DeliveryChanged(val messageId: Long, val state: DeliveryState) : CoreEvent
    data class NodeSeen(val node: NodeInfo) : CoreEvent
    data class ResourceProgress(val peerId: String, val messageId: Long, val received: Int, val total: Int) : CoreEvent
    data class CoreError(val message: String) : CoreEvent
}

/**
 * Offline/demo implementation used when no Rust core is linked and no radio is connected.
 *
 * It keeps the UI state machine honest (messages move QUEUED → SENT → DELIVERED) and never
 * claims to have talked to a radio. Everything it returns is derived from [DemoData].
 */
class DemoEngineBridge : EngineBridge {
    private val _status = MutableStateFlow(CoreStatus(running = true, nodeIdHex = "a1b2c3d4e5f60718"))
    override val status: StateFlow<CoreStatus> = _status.asStateFlow()

    private val _events = MutableSharedFlow<CoreEvent>(extraBufferCapacity = 32)
    override val events: SharedFlow<CoreEvent> = _events.asSharedFlow()

    private val nextId = AtomicLong(10_000L)

    override suspend fun start() {
        _status.value = _status.value.copy(running = true)
    }

    override suspend fun stop() {
        _status.value = CoreStatus(running = false)
    }

    override suspend fun sendText(targetId: String, text: String, channel: Boolean): Result<Long> {
        val id = nextId.incrementAndGet()
        _events.tryEmit(
            CoreEvent.MessageReceived(
                Message(
                    id = id,
                    peerId = if (channel) targetId else targetId,
                    fromId = selfNodeId() ?: "demo",
                    toId = targetId,
                    kind = MessageKind.TEXT,
                    text = text,
                    sentAtMs = System.currentTimeMillis(),
                    outgoing = true,
                    delivery = DeliveryState.SENT,
                ),
            ),
        )
        return Result.success(id)
    }

    override suspend fun ingest(frame: ByteArray, rssi: Int?, snr: Float?) {
        // No frame processing without the Rust core; report so callers can surface the gap.
        _events.tryEmit(CoreEvent.CoreError("demo engine cannot ingest OMP frames (link openmesh-ffi at M2)"))
    }

    override suspend fun nodes(): List<NodeInfo> = emptyList()

    override suspend fun messages(peerId: String): List<Message> = emptyList()

    override fun selfNodeId(): String? = _status.value.nodeIdHex
}

/**
 * Placeholder for the UniFFI-backed engine. It is intentionally not used by the repository
